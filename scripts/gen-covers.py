#!/usr/bin/env python3
"""Generate Covers.swift: the eShop icon URL (Nintendo's own CDN) of every game the launcher lists.

Usage: python3 -I scripts/gen-covers.py US.en.json HK.zh.json JP.ja.json <nxnative>/dm/games > Covers.swift
(the region files of titledb; US first, then HK and JP for the Asian releases)

The titledb files (github.com/blawar/titledb) are read as data, for their id -> iconUrl pairs; only URLs on
img-eshop.cdn.nintendo.net are kept. No image is downloaded or stored here: the launcher fetches an icon when the game
is first shown and keeps it in ~/Library/Caches. Games without an entry show the placeholder icon.
"""
import json
import re
import sys
from pathlib import Path

MACNATIVE = ["0100F2C0115B6000", "01007EF00011E000"]
CDN = re.compile(r"^https://img-eshop\.cdn\.nintendo\.net/i/[0-9a-f]{64}\.jpg$")


def main(dbs, games_dir):
    ids = set(MACNATIVE)
    ids |= {d.name.upper() for d in Path(games_dir).iterdir() if (d / "game.tsv").is_file()}
    catalog = Path(__file__).resolve().parent.parent / "NXCatalog.swift"
    ids |= set(re.findall(r'id: "(0[0-9A-F]{15})"', catalog.read_text(encoding="utf-8")))
    urls = {}
    for db in dbs:   # the first file that has a game wins
        for v in json.load(open(db, encoding="utf-8")).values():
            i, u = (v.get("id") or "").upper(), v.get("iconUrl") or ""
            if i in ids and i not in urls and CDN.match(u):
                urls[i] = u
    print("// GENERATED by scripts/gen-covers.py from titledb (github.com/blawar/titledb). Do not edit by hand.")
    print("// Icon URLs on Nintendo's eShop CDN, by title ID; the images themselves are fetched at run time and cached.")
    print("")
    print("let coverURLs: [String: String] = [")
    for i in sorted(urls):
        print(f'    "{i}": "{urls[i]}",')
    print("]")
    print(f"// {len(urls)} of {len(ids)} games; without an icon: {', '.join(sorted(ids - set(urls)))}", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    main(sys.argv[1:-1], sys.argv[-1])
