def swift(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def profile(d):
    rows = []
    for line in (d / "game.tsv").read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        c = line.split("\t")
        rows.append((c[0].strip(), [v.strip() for v in c[1:]]))
    one = lambda k, default="": next((v[0] for kk, v in rows if kk == k and v), default)
    builds = [(v[0], v[1]) for k, v in rows if k == "build" and len(v) >= 2]
    package = one("package", builds[-1][0] if builds else "")
    fps = one("fps_target", "0")
    return dict(id=one("title_id", d.name).upper(), name=one("name", d.name), builds=builds, package=package,
                fps=int(fps) if fps.isdigit() else 0)


def main(root):
    games = [profile(d) for d in sorted(Path(root).iterdir()) if (d / "game.tsv").is_file()]
    games.sort(key=lambda g: g["name"].lower())
    print("// GENERATED by scripts/gen-catalog.py from nxnative's dm/games/*/game.tsv. Do not edit by hand.")
    print("// The launcher also reads a checked-out nxnative at run time (loadNXCatalog), so newer games and versions show up after an update.")
    print("")
    print("let nxBuiltinCatalog: [NXGameInfo] = [")
    for g in games:
        builds = ", ".join(f"({swift(v)}, {swift(d)})" for v, d in g["builds"])
        zh = swift(ZH[g["id"]]) if g["id"] in ZH else "nil"
        print(f"    NXGameInfo(id: {swift(g['id'])}, name: {swift(g['name'])}, zh: {zh}, builds: [{builds}], "
              f"package: {swift(g['package'])}, fps: {g['fps']}),")
    print("]")
    print(f"// {len(games)} games", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
